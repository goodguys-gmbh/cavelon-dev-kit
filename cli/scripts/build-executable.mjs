// Build the standalone executable of `cavelon` with Bun (`bun build --compile`),
// for the system this runs on: build/cavelon-<os>-<arch>[.exe]. Run `npm run build`
// first; this bundles dist/ with the Bun runtime into one file that needs no Node.js.
//
// The executable has no package.json and no dist/skills/ beside it, so a generated
// entry (dist/executable.js) hands it the version and the skills before the CLI
// loads (src/embedded.ts). The native credential store binding (@napi-rs/keyring)
// is the one npm installed for this system, which is why each executable is built
// on its own platform rather than cross-compiled.
//
//   bun scripts/build-executable.mjs       (npm run build:executable)
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const cli = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(cli, "dist");

const OS = { darwin: "darwin", linux: "linux", win32: "windows" }[process.platform];
const ARCH = { x64: "x64", arm64: "arm64" }[process.arch];
if (!OS || !ARCH) throw new Error(`No standalone executable for ${process.platform}/${process.arch}.`);
if (!existsSync(path.join(dist, "cli.js")) || !existsSync(path.join(dist, "skills"))) {
  throw new Error("Run `npm run build` first: dist/cli.js or dist/skills/ is missing.");
}

const version = JSON.parse(readFileSync(path.join(cli, "package.json"), "utf8")).version;

/** The skills as `bundledSkills()` reads them from dist/skills/: sorted, with LF line ends. */
function readSkills(root) {
  const skills = [];
  const names = readdirSync(root, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .toSorted((a, b) => a.localeCompare(b, "en"));
  for (const name of names) {
    const files = [];
    const walk = (sub) => {
      for (const item of readdirSync(path.join(root, name, sub), { withFileTypes: true })) {
        const relative = sub ? `${sub}/${item.name}` : item.name;
        if (item.isDirectory()) walk(relative);
        else if (item.isFile()) files.push({ path: relative, content: readFileSync(path.join(root, name, relative), "utf8").replaceAll("\r\n", "\n") });
      }
    };
    walk("");
    if (files.some((f) => f.path === "SKILL.md")) skills.push({ name, files: files.toSorted((a, b) => a.path.localeCompare(b.path, "en")) });
  }
  return skills;
}

const skills = readSkills(path.join(dist, "skills"));
if (!skills.length) throw new Error("dist/skills/ holds no skills.");

// A dynamic import, so the CLI's modules (and KIT_VERSION) load after `embed`.
const entry = path.join(dist, "executable.js");
writeFileSync(
  entry,
  [
    "// Generated by scripts/build-executable.mjs: the entry of the standalone executable.",
    'import { embed } from "./embedded.js";',
    `embed(${JSON.stringify({ version, skills })});`,
    'await import("./cli.js");',
    "",
  ].join("\n"),
);

// x64 Linux and Windows use Bun's baseline runtime, which runs on processors
// without AVX2 (older machines, some virtual machines).
const target = `bun-${OS}-${ARCH}${ARCH === "x64" && OS !== "darwin" ? "-baseline" : ""}`;
const outfile = path.join(cli, "build", `cavelon-${OS}-${ARCH}${OS === "windows" ? ".exe" : ""}`);
mkdirSync(path.dirname(outfile), { recursive: true });

const args = [
  "build",
  entry,
  "--compile",
  `--target=${target}`,
  `--outfile=${outfile}`,
  // The npm build reads no .env or bunfig.toml from the folder it runs in;
  // neither does the executable, so a repository cannot change its settings.
  "--no-compile-autoload-dotenv",
  "--no-compile-autoload-bunfig",
];
if (OS === "windows") {
  args.push(
    "--windows-title=cavelon",
    "--windows-publisher=goodguys GmbH",
    `--windows-version=${version.split("-")[0]}.0`,
    "--windows-description=cavelon: CLI and MCP server for Cavelon solutions",
    "--windows-copyright=goodguys GmbH, Apache-2.0",
  );
}

// Run by Bun, so the bun that builds is the one running this script.
if (!process.versions.bun) throw new Error("Run this with Bun (https://bun.sh): npm run build:executable.");
const result = spawnSync(process.execPath, args, { cwd: cli, stdio: "inherit" });
if (result.error) throw new Error(`Could not run ${process.execPath}: ${result.error.message}.`);
if (result.status !== 0) process.exit(result.status ?? 1);

// macOS's keychain gives an item back only to a program with a code signature
// (an unsigned one fails with "The user name or passphrase you entered is not
// correct"). Bun signs ad hoc on Apple silicon only; sign every macOS build so.
// The release signs it again with the company's Developer ID.
if (OS === "darwin") {
  const signed = spawnSync("/usr/bin/codesign", ["--force", "--sign", "-", outfile], { stdio: "inherit" });
  if (signed.status !== 0) process.exit(signed.status ?? 1);
}
process.stdout.write(`${outfile}\n`);
